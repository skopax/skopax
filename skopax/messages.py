HELD: list[tuple[dict[str, dict[str, str]], tuple[str, ...]]] = [({}, (ENGLISH,))]
LANGUAGE: list[Callable[[], str] | None] = [None]
WARNED: set[tuple[str, str]] = set()
WARNED_GUARD = threading.Lock()
SPEAKING: contextvars.ContextVar[str | None] = contextvars.ContextVar('skopax_speaking', default=None)


def fields(text: str) -> frozenset[str] | None:
    try:
        return frozenset(name for _, name, _, _ in string.Formatter().parse(text) if name is not None)
    except ValueError:
        return None


def plain(text: str) -> bool:
    try:
        return not any(name is not None and (spec or conversion is not None) for _, name, spec, conversion in string.Formatter().parse(text))
    except ValueError:
        return False


def primary(lang) -> str:
    return str(lang).split('-', 1)[0].lower()


def printable(value, limit: int = SHOWN_MAX) -> str:
    return ''.join(ch if ch.isprintable() else '?' for ch in str(value)[:limit])


def refusal(lang, key, text) -> str | None:
    if not isinstance(lang, str) or not LANG_TAG.fullmatch(lang):
        return msg('locales.why.lang')
    if primary(lang) == ENGLISH:
        return msg('plugins.why.locale_english')
    if not isinstance(key, str) or key not in MESSAGES:
        return msg('locales.why.key')
    if not isinstance(text, str):
        return msg('locales.why.text')
    if len(text) > TEXT_MAX:
        return msg('locales.why.long', limit=TEXT_MAX)
    if any(unicodedata.category(ch) == 'Cc' and ch != '\n' for ch in text):
        return msg('locales.why.control')
    if fields(text) != fields(MESSAGES[key]):
        return msg('locales.why.fields')
    if not plain(text):
        return msg('locales.why.format')
    return None


def warn_once(lang, key, reason: str) -> None:
    with WARNED_GUARD:
        if (lang, key) in WARNED:
            return
        WARNED.add((lang, key))
    log.warning('%s', msg('locales.dropped', lang=printable(lang), key=printable(key), reason=reason))


def set_catalogs(packs: Sequence[tuple[str, Mapping[str, str]]]) -> list[tuple[str, str]]:
    kept: dict[str, dict[str, str]] = {}
    dropped: list[tuple[str, str]] = []
    for lang, entries in packs:
        for key, text in entries.items():
            why = refusal(lang, key, text)
            if why is None:
                kept.setdefault(lang, {})[key] = text
                continue
            dropped.append((lang, key))
            warn_once(lang, key, why)
    HELD[0] = (kept, (ENGLISH,) + tuple(sorted(lang for lang in kept if lang != ENGLISH)))
    return dropped


def catalog(lang: str) -> dict:
    return dict(HELD[0][0].get(lang, {}))


def languages() -> tuple[str, ...]:
    return HELD[0][1]


def use_language(get: Callable[[], str] | None) -> None:
    LANGUAGE[0] = get


@contextlib.contextmanager
def speaking(lang: str | None) -> Iterator[None]:
    token = SPEAKING.set(lang)
    try:
        yield
    finally:
        SPEAKING.reset(token)


def language() -> str:
    known = HELD[0][1]
    asked = SPEAKING.get()
    if asked:
        return asked if asked in known else next((pack for pack in known if primary(pack) == primary(asked)), ENGLISH)
    get = LANGUAGE[0]
    lang = get() if get is not None else ENGLISH
    return lang if lang in known else ENGLISH


def reset() -> None:
    HELD[0] = ({}, (ENGLISH,))
    LANGUAGE[0] = None
    with WARNED_GUARD:
        WARNED.clear()


def msg(key: str, /, **values) -> str:
    english = MESSAGES[key]
    filled = {'product': brand.product()} | values
    if key.partition('.')[0] in OUTBOUND:
        lang = language()
        text = HELD[0][0].get(lang, {}).get(key)
        if text is not None:
            try:
                return text.format(**filled)
            except (KeyError, IndexError, ValueError, TypeError, AttributeError):
                warn_once(lang, key, msg('locales.why.format'))
    return english.format(**filled)


FOLD_LETTERS = {'\u0131': 'i', '\u0142': 'l', '\u00f8': 'o', '\u0111': 'd', '\u00f0': 'd', '\u00fe': 'th', '\u00df': 'ss', '\u00e6': 'ae', '\u0153': 'oe', '\u0127': 'h'}
FOLD_TABLE = str.maketrans(FOLD_LETTERS)


def fold(text: str) -> str:
    decomposed = unicodedata.normalize('NFKD', text)
    return ''.join(ch for ch in decomposed if not unicodedata.combining(ch)).casefold().translate(FOLD_TABLE)
